PRE_OPTIONS  = ['موجود', 'جزء منها', 'غير موجود']
POST_OPTIONS = ['انجز', 'نوعاً ما', 'لم ينجز']


class Command(BaseCommand):
    help = 'يزرع مقياس "المهارات الحركية الدقيقة لبرنامج بورتيج" ببياناته الكاملة (111 مهارة عبر 6 فئات عمرية).'

    @transaction.atomic
    def handle(self, *args, **options):
        assessment, created = Assessment.objects.get_or_create(
            name=ASSESSMENT_NAME,
            defaults={
                'description': 'مقياس بورتيج لتنمية المهارات الحركية الدقيقة، من عمر يوم واحد حتى 6 سنوات — '
                               'جمع وإعداد أ. موضي بعومه، مركز رواد التأهيل لرعاية ذوي الاحتياجات الخاصة.',
                'is_active': True,
            },
        )
        if not created:
            self.stdout.write(self.style.WARNING(
                f'المقياس "{ASSESSMENT_NAME}" موجود مسبقًا (id={assessment.id}) — لن يُعاد إنشاؤه.'
            ))
            return

        for kind, labels in (('pre', PRE_OPTIONS), ('post', POST_OPTIONS)):
            for order, label in enumerate(labels):
                AssessmentScaleOption.objects.create(
                    assessment=assessment, kind=kind, label=label, order=order,
                )

        total_questions = 0
        for sec_order, (section_name, items) in enumerate(SECTIONS):
            section = AssessmentSection.objects.create(
                assessment=assessment, name=section_name, order=sec_order,
            )
            for q_order, text in enumerate(items):
                AssessmentQuestion.objects.create(
                    assessment=assessment, section=section, text=text, order=q_order,
                )
                total_questions += 1

        self.stdout.write(self.style.SUCCESS(
            f'تم إنشاء المقياس "{ASSESSMENT_NAME}" (id={assessment.id}) — '
            f'{len(SECTIONS)} فئات عمرية، {total_questions} مهارة، 6 خيارات تقدير.'
        ))
